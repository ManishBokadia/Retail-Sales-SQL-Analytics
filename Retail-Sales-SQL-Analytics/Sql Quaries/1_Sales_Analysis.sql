 BUSINESS QUESTION 6
*******************************************************************************

Question:
What is the cumulative sales over time?

Business Objective:
Track business growth using a running total.

SQL Concepts Used:
• CTE
• Window Functions
• SUM() OVER()


******************************************************************************/

WITH monthly_sales AS

(

SELECT

    YEAR(order_date) AS order_year,

    MONTH(order_date) AS order_month,

    SUM(sales) AS total_sales

FROM sales

GROUP BY

    YEAR(order_date),

    MONTH(order_date)

)

SELECT

    order_year,

    order_month,

    ROUND(total_sales,2) AS monthly_sales,

    ROUND(

        SUM(total_sales) OVER(

            ORDER BY

            order_year,

            order_month

        ),

        2

    ) AS running_sales

FROM monthly_sales;

/*
Business Insight:

Running sales allows management to monitor cumulative business growth.

It helps answer questions like:

• Is the company growing consistently?

• At what point did sales accelerate?

• When did growth slow down?

Running totals are widely used in executive dashboards.
*/


